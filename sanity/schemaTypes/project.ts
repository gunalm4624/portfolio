import { defineField, defineType } from "sanity";

export default defineType({
  name: "project",
  title: "Project",
  type: "document",
  fields: [
    defineField({
      name: "name",
      title: "Name",
      type: "string",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "image",
      title: "Image",
      type: "image",
      options: { hotspot: true },
    }),
    defineField({
      name: "accent",
      title: "Accent color",
      description:
        "Only used for the placeholder card when no image is set. Not required.",
      type: "string",
      options: {
        list: [
          { title: "Orange", value: "orange" },
          { title: "Zinc", value: "zinc" },
        ],
      },
      initialValue: "zinc",
    }),
    defineField({
      name: "order",
      title: "Order",
      type: "number",
      initialValue: 0,
    }),
  ],
  orderings: [
    {
      title: "Order",
      name: "orderAsc",
      by: [{ field: "order", direction: "asc" }],
    },
  ],
  preview: {
    select: { title: "name", subtitle: "accent", media: "image" },
  },
});
